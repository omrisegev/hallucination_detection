"""Write TABLES.md from BOOT.csv (value [95% CI]) and RESULTS*.csv (within-AUC, flag rate, macro SLA)."""
import csv, glob
from collections import defaultdict
from pathlib import Path
HERE = Path(__file__).resolve().parent
P = ['qwen_prm_7b', 'qwen_prm_72b', 'pure_prm', 'rlhflow_prm']
H = '| arm | Qwen-PRM-7B | Qwen-PRM-72B | PURE | RLHFlow |\n|---|---|---|---|---|'
B = defaultdict(dict); R = defaultdict(dict)
for r in csv.DictReader(open(HERE / 'BOOT.csv')):
    B[(r['bench'], r['kind'], r['arm'])][r['prm']] = tuple(float(r[k]) for k in ('value', 'lo', 'hi'))
for f in glob.glob(str(HERE / 'RESULTS*.csv')):
    for r in csv.DictReader(open(f)):
        R[(r['bench'], r['metric'], r['arm'])][r['prm']] = float(r['value'])
ORDER = ['GSP-T own count', 'GSP-T + GAP', 'GSP-T hyb10 own count', 'GSP-T hyb10 + GAP', 'GSP-T hyb30 own count',
         'GSP-T hyb30 + GAP', 'CP GSP-T rank (free EM)', 'CP GSP-T rank (free, pi = 1/2)',
         'CP GSP-T hyb10 rank (free, pi = 1/2)', 'CP GSP-T hyb30 rank (free, pi = 1/2)',
         'GSP full (PRM + tele) own count', 'GSP full (PRM + tele) + GAP', 'CP PRM + GSP full rank (anchored)',
         'PRM native', 'PRM + GAP', 'CP PRM (anchored)']
NAME = {'prmbench': 'PRMBench (official PRMScore)', 'socratic': 'Socratic-PRMBench (official PRMScore)',
        'hard2verify': 'Hard2Verify (official balanced F1)', 'processbench': 'ProcessBench (official average F1)'}
out = []
for b, nm in NAME.items():
    out += [f'## {nm}', '', '### Absolute value [95% bootstrap CI]', '', H]
    for a in ORDER:
        v = B.get((b, 'abs', a))
        if v: out.append(f'| {a} | ' + ' | '.join(f'{v[p][0]:.1f} [{v[p][1]:.1f}, {v[p][2]:.1f}]' if p in v else '-' for p in P) + ' |')
    out += ['', '### Paired differences [95% bootstrap CI]', '', H]
    for (bb, k, a), v in B.items():
        if bb == b and k == 'diff':
            out.append(f'| {a.replace(" MINUS ", " minus ")} | ' + ' | '.join(f'{v[p][0]:+.1f} [{v[p][1]:+.1f}, {v[p][2]:+.1f}]' if p in v else '-' for p in P) + ' |')
    met = 'macro SLA' if b == 'processbench' else 'within-AUC'
    out += ['', f'### {met} and flag rate (%)', '', H]
    for a in ORDER:
        v, fr = R.get((b, met, a)), R.get((b, 'flag rate', a))
        if v: out.append(f'| {a} | ' + ' | '.join((f'{v[p]:.3f}' if met == 'within-AUC' else f'{v[p]:.1f}') + (f' / {fr[p]:.1f}%' if fr and p in fr else '') if p in v else '-' for p in P) + ' |')
    out.append('')
open(HERE / 'TABLES.md', 'w').write('# GSP ablation tables (generated by make_tables.py)\n\n' + '\n'.join(out))
