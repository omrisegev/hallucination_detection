"""RESULTS_prm.csv + RESULTS_sa.csv -> TABLES.md (headline metric per competitor benchmark, both modes)."""
import csv
from pathlib import Path

HERE = Path(__file__).resolve().parent
PRMS = [('qwen_prm_7b', 'Qwen-PRM-7B'), ('qwen_prm_72b', 'Qwen-PRM-72B'), ('pure_prm', 'PURE'), ('rlhflow_prm', 'RLHFlow')]
SA = {'qwen_prm_7b': 'Qwen2.5-Math-7B-Instruct', 'qwen_prm_72b': 'Qwen2.5-Math-72B-Instruct', 'pure_prm': 'Qwen2.5-Math-7B',
      'rlhflow_prm': 'Llama-3.1-8B-Instruct'}
R = [r for m in ('prm', 'sa') for r in csv.DictReader(open(HERE / f'RESULTS_{m}.csv'))]


def v(mode, prm, bench, proto, arm, metric, **kw):
    hits = [r for r in R if r['mode'] == mode and r['prm'] == prm and r['benchmark'] == bench and r['protocol'] == proto
            and r['arm'] == arm and r['metric'] == metric and all(r.get(k, '') == x for k, x in kw.items())]
    assert len(hits) == 1, (mode, prm, bench, proto, arm, metric, kw, len(hits))
    return float(hits[0]['value'])


def table(title, note, cols, getter):
    out = [f'## {title}', '', '| PRM | ' + ' | '.join(c for c, _ in cols) + ' |', '|---|' + '---|' * len(cols)]
    for p, name in PRMS:
        out.append(f'| {name} | ' + ' | '.join(f'{getter(p, *spec):.2f}' if spec[2] not in ('auroc', 'within-AUC') else f'{getter(p, *spec):.3f}'
                                             for _, spec in cols) + ' |')
    return out + ([f'- {note}'] if note else []) + ['']


L = ['# C4U and TELE16 on every competitor benchmark, PRM backbone (bb) and standalone base model (sa)', '',
     'Generated by `tables.py` from `RESULTS_prm.csv` / `RESULTS_sa.csv` (`run_all.py`). PRM native = the PRM at its own threshold '
     '(identical in both modes: same rewards). Standalone models: ' + ', '.join(f'{n} -> {SA[p]}' for p, n in PRMS) + '.', '']

pb = lambda p, mode, arm, metric, kw: v(mode, p, 'prmbench', 'PRISM T2', arm, metric, **kw)
L += table('PRMBench, PRISM Table 2 PRMScore (own flags; PRM at native threshold)', 'PRISM (retrained 7B) 68.00. TELE16 was selected on PRMBench (in-sample).',
           [('PRM native', ('prm', 'PRM native', 'PRMScore', {'pool': 'non-control', 'rule': 'native'})),
            ('TELE16 bb', ('prm', 'TELE_N16', 'PRMScore', {'pool': 'non-control', 'rule': 'GAP'})),
            ('C4U bb', ('prm', 'C4U', 'PRMScore', {'pool': 'non-control', 'rule': 'GAP'})),
            ('TELE16 sa', ('sa', 'TELE_N16', 'PRMScore', {'pool': 'non-control', 'rule': 'GAP'})),
            ('C4U sa', ('sa', 'C4U', 'PRMScore', {'pool': 'non-control', 'rule': 'GAP'}))],
           lambda p, mode, arm, metric, kw: pb(p, mode, arm, metric, kw))

sl = lambda p, mode, arm, metric, kw: v(mode, p, 'prmbench', 'SLIDER', arm, metric, **kw)
L += table('PRMBench redundancy, SLIDER: balanced accuracy, LR threshold (balanced), all steps', 'Step-RRI (paper) 61.91 plain accuracy; majority class 86.8 plain accuracy.',
           [(f'{a} {m}', (mode, arm, 'bal_acc', {'scope': 'all_steps', 'rule': 'LR threshold balanced'}))
            for a, arm in (('PRM', 'PRM native'),) for m, mode in (('', 'prm'),)] +
           [(f'{a} {m}', (mode, arm, 'bal_acc', {'scope': 'all_steps', 'rule': 'LR threshold balanced'}))
            for a, arm in (('TELE16', 'TELE_N16'), ('C4U', 'C4U')) for m, mode in (('bb', 'prm'), ('sa', 'sa'))], sl)

pbt = lambda p, mode, arm, metric, kw: v(mode, p, 'processbench', kw.pop('proto'), arm, metric, **kw)
for metric, proto, note in (('average F1', 'PRISM PB T6', 'Own label-free flags (C4U: DS count; TELE16: GAP). Both flag at least one step in almost every answer, so correct-answer accuracy and F1 collapse. With the PRM deciding whether an answer has an error (NC rule), see c4u_vs_competitors_v1/RESULTS_PB_NC.csv.'),
                            ('macro SLA', 'MtG T3 SLA', 'Mind the Gap (Shannon Drop, Qwen3-8B, no PRM): macro SLA 39.39.')):
    L += table(f'ProcessBench, {proto}: {metric}', note,
               [('PRM native', ('prm', 'PRM native', metric, {'proto': proto}))] +
               [(f'{a} {m}', (mode, arm, metric, {'proto': proto})) for a, arm in (('TELE16', 'TELE_N16'), ('C4U', 'C4U'))
                for m, mode in (('bb', 'prm'), ('sa', 'sa'))], lambda p, mode, arm, metric, kw: pbt(p, mode, arm, metric, dict(kw)))

CROP_PAPER = {'prmbench': 'Trace+PRM LR 21.8, Direct PRM 4.8', 'processbench': 'Trace+PRM LR 42.4, Direct PRM 46.7',
              'crv_arith': 'Trace+PRM LR 97.1, Direct PRM 97.5', 'crv_gsm8k': 'Trace+PRM LR 63.1, Direct PRM 81.7',
              'prm800k': 'Trace+PRM LR 89.5, Direct PRM 67.2', 'math_shepherd': 'Direct PRM AUROC .454, kept 1.0 (its labels look degenerate: every arm is below .5 AUROC, as in CROP)'}
for bench in ('prmbench', 'processbench', 'crv_arith', 'crv_gsm8k', 'prm800k', 'math_shepherd'):
    prm_arm = 'PRM (1-reward)'
    L += table(f'{bench}, CROP Table 6 (alpha .05): prefix kept %, q201 grid', f'CROP paper (Qwen-PRM-7B): {CROP_PAPER[bench]}. Thresholds calibrated with labels for every row.',
               [('PRM', ('prm', prm_arm, 'kept', {'grid': 'q201'}))] +
               [(f'{a} {m}', (mode, arm, 'kept', {'grid': 'q201'})) for a, arm in (('TELE16', 'TELE_N16'), ('C4U', 'C4U'))
                for m, mode in (('bb', 'prm'), ('sa', 'sa'))],
               lambda p, mode, arm, metric, kw, b=bench: v(mode, p, b, 'CROP T6', arm, metric, **kw))
    L += table(f'{bench}, CROP Table 6: pooled step AUROC (test steps)', '',
               [('PRM', ('prm', prm_arm, 'auroc', {'grid': 'q201'}))] +
               [(f'{a} {m}', (mode, arm, 'auroc', {'grid': 'q201'})) for a, arm in (('TELE16', 'TELE_N16'), ('C4U', 'C4U'))
                for m, mode in (('bb', 'prm'), ('sa', 'sa'))],
               lambda p, mode, arm, metric, kw, b=bench: v(mode, p, b, 'CROP T6', arm, metric, **kw))

for bench in sorted({r['benchmark'] for r in R if r['protocol'] == 'ARES-style'}):
    for metric in ('macro-F1 (own flags)', 'within-AUC'):
        L += table(f'{bench}, ARES-style: {metric}', 'ARES gives no subset size; population = the common answers of all cells (counts below).' if metric == 'within-AUC' else '',
                   [('PRM native', ('prm', 'PRM native', metric, {}))] +
                   [(f'{a} {m}', (mode, arm, metric, {})) for a, arm in (('TELE16', 'TELE_N16'), ('C4U', 'C4U'))
                    for m, mode in (('bb', 'prm'), ('sa', 'sa'))],
                   lambda p, mode, arm, metric, kw, b=bench: v(mode, p, b, 'ARES-style', arm, metric, **kw))
    L += [f'- {bench} population: ' + ', '.join(f"{n} {int(v('prm', p, bench, 'ARES-style', 'population', 'answers'))} answers / "
                                                 f"{int(v('prm', p, bench, 'ARES-style', 'population', 'steps'))} steps" for p, n in PRMS), '']

(HERE / 'TABLES.md').write_text('\n'.join(L), encoding='utf-8')
print('\n'.join(L))
